def _deep_merge(base: dict[str, Any], overlay: Mapping[str, Any]) -> dict[str, Any]:
    result = copy.deepcopy(base)
    for key, value in overlay.items():
        if isinstance(value, Mapping) and isinstance(result.get(key), Mapping):
            result[key] = _deep_merge(dict(result[key]), value)
        else:
            result[key] = copy.deepcopy(value)
    return result


class Settings:
    """Read-only view over the merged configuration."""

    def __init__(self, data: dict[str, Any]) -> None:
        # Defensive copy so callers can keep mutating their dict safely.
        self.raw = copy.deepcopy(data)
        self._validate()

    def get(self, dotted: str, default: Any = None) -> Any:
        node: Any = self.raw
        for part in dotted.split("."):
            if not isinstance(node, Mapping) or part not in node:
                return default
            node = node[part]
        return node

    def section(self, name: str) -> dict[str, Any]:
        value = self.raw.get(name, {})
        return value if isinstance(value, dict) else {}

    def enabled(self, service: str) -> bool:
        value = self.section("services").get(service, False)
        return bool(value)

    @property
    def log_dir(self) -> Path:
        return Path(self.raw["log_dir"])

    @property
    def state_dir(self) -> Path:
        return Path(self.raw["state_dir"])

    @property
    def run_dir(self) -> Path:
        return Path(self.raw["run_dir"])

    @property
    def master_user(self) -> str:
        return str(self.raw["master_user"])

    @property
    def db_engine(self) -> str:
        return str(self.get("database.engine", "sqlite"))

    @property
    def sqlite_path(self) -> Path:
        return Path(self.get("database.sqlite_path"))

    @property
    def backend_bind(self) -> str:
        return str(self.get("backend.bind", "127.0.0.1"))

    @property
    def backend_port(self) -> int:
        return int(self.get("backend.port", 8080))

    @property
    def backend_url(self) -> str:
        host = self.backend_bind
        if host in {"0.0.0.0", "::"}:
            host = "127.0.0.1"
        if ":" in host and not host.startswith("["):
            host = f"[{host}]"
        return f"http://{host}:{self.backend_port}"

    def as_dict(self) -> dict[str, Any]:
        return copy.deepcopy(self.raw)

    def _validate(self) -> None:
        errors: list[str] = []
        for dotted in _ABSOLUTE_KEYS:
            value = self.get(dotted)
            if value is not None and not str(value).startswith("/"):
                errors.append(f"{dotted} must be an absolute path")
        user = str(self.raw.get("master_user", ""))
        if not USERNAME_RE.match(user):
            errors.append("master_user is not a valid Unix user name")
        engine = self.get("database.engine")
        if engine not in {"sqlite", "mariadb"}:
            errors.append("database.engine must be 'sqlite' or 'mariadb'")
        try:
            port = int(self.get("backend.port", 0))
            if not 1 <= port <= 65535:
                errors.append("backend.port must be between 1 and 65535")
        except (TypeError, ValueError):
            errors.append("backend.port must be an integer")
        try:
            ipaddress.ip_address(str(self.get("backend.bind")))
        except ValueError:
            errors.append("backend.bind must be an IPv4 or IPv6 address")
        for key in ("monitor.interval", "monitor.max_attempts", "boot.timeout_seconds"):
            try:
                if int(self.get(key, 0)) <= 0:
                    errors.append(f"{key} must be positive")
            except (TypeError, ValueError):
                errors.append(f"{key} must be an integer")
        for key in ("keep_daily", "keep_weekly", "keep_monthly", "keep_yearly"):
            try:
                if int(self.get(f"backup.{key}", -1)) < 0:
                    errors.append(f"backup.{key} must be >= 0")
            except (TypeError, ValueError):
                errors.append(f"backup.{key} must be an integer")
        subset = str(self.get("backup.verify_subset", ""))
        if not re.match(r"^(?:[1-9][0-9]?%|[1-9][0-9]*/[1-9][0-9]*|10%|100%)$", subset):
            errors.append("backup.verify_subset must look like '5%' or '1/10'")
        services = self.raw.get("services")
        if not isinstance(services, dict):
            errors.append("services must be an object")
        else:
            for key, value in services.items():
                if not re.match(r"^[a-z][a-z0-9-]*$", str(key)):
                    errors.append(f"invalid service key: {key!r}")
                if not isinstance(value, bool):
                    errors.append(f"services.{key} must be a boolean")
        if errors:
            raise ConfigError("; ".join(errors))


def _env_settings(env: Mapping[str, str]) -> dict[str, Any]:
    overlay: dict[str, Any] = {}
    simple = {
        "ETA_HOSTNAME": ("hostname", str),
        "ETA_MASTER_USER": ("master_user", str),
        "ETA_LOG_DIR": ("log_dir", str),
        "ETA_STATE_DIR": ("state_dir", str),
        "ETA_RUN_DIR": ("run_dir", str),
        "ETA_DB_ENGINE": ("database.engine", str),
        "ETA_SQLITE_PATH": ("database.sqlite_path", str),
        "ETA_BACKEND_BIND": ("backend.bind", str),
        "ETA_BACKEND_PORT": ("backend.port", int),
        "ETA_BACKUP_REPOSITORY": ("backup.repository", str),
        "ETA_RESTIC_PASSWORD_FILE": ("backup.password_file", str),
    }
    for env_key, (dotted, cast) in simple.items():
        if env_key not in env or env[env_key] == "":
            continue
        try:
            value = cast(env[env_key])
        except ValueError as exc:
            raise ConfigError(f"{env_key}: {exc}") from exc
        node = overlay
        parts = dotted.split(".")
        for part in parts[:-1]:
            node = node.setdefault(part, {})
        node[parts[-1]] = value
    return overlay


def load_settings(
    config_dir: str | os.PathLike[str] | None = None,
    env: Mapping[str, str] | None = None,
    *,
    strict: bool = True,
) -> Settings:
    env = os.environ if env is None else env
    directory = Path(config_dir or env.get("ETA_CONFIG_DIR", "/etc/eta"))
    data = copy.deepcopy(DEFAULT_SETTINGS)
    data["config_dir"] = str(directory)
    for name in ("defaults.json", "settings.json"):
        layer = read_json(directory / name)
        if isinstance(layer, dict):
            data = _deep_merge(data, layer)
    explicit = env.get("ETA_SETTINGS")
    if explicit:
        layer = read_json(explicit)
        if not isinstance(layer, dict):
            raise ConfigError(f"cannot read settings file: {explicit}")
        data = _deep_merge(data, layer)
    data = _deep_merge(data, _env_settings(env))
    try:
        return Settings(data)
    except ConfigError:
        if strict:
            raise
        return Settings(copy.deepcopy(DEFAULT_SETTINGS))


def service_enabled(settings: Settings, service: str) -> bool:
    """Configured enablement, accounting for the selected database engine."""
    if service == "mariadb":
        return settings.db_engine == "mariadb" and settings.enabled("mariadb")
    if service == "database":
        return settings.enabled("database")
    return settings.enabled(service)
