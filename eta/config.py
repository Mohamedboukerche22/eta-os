"""Layered, validated Eta OS configuration.

Layers, lowest priority first:

1. Built-in defaults (this file).
2. ``<config_dir>/defaults.json`` generated by the NixOS module.
3. ``<config_dir>/settings.json`` written by the installer/administrator.
4. ``ETA_SETTINGS`` (explicit file) or environment overrides.

Nothing in this module ever stores a password. Password material lives in
PAM/shadow (admin login), the restic password file, or a MariaDB option file.
"""

